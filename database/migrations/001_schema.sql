/*
  Kinetix — Esquema PostgreSQL (migración 001)

  Estado final y consolidado del modelo de datos. Reemplaza a kinetix_core.sql,
  a las migraciones T-SQL 001–005 y al DDL que antes se creaba en tiempo de ejecución.

  Convenciones:
   - Identificadores en PascalCase sin comillas (Postgres los almacena en minúsculas;
     server/core/db.js restaura la capitalización al devolver filas).
   - BOOLEAN para banderas, TIMESTAMPTZ para fechas con hora (siempre UTC), UUID para archivos.
   - Los emails usan CITEXT para conservar la comparación sin distinguir mayúsculas.
*/

CREATE EXTENSION IF NOT EXISTS citext;

/* ── Organización ─────────────────────────────────────────────────────── */
CREATE TABLE Companies
(
    Id              INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Companies PRIMARY KEY,
    Name            VARCHAR(150) NOT NULL,
    Rnc             VARCHAR(20) NOT NULL,
    LogoUrl         VARCHAR(500) NULL,
    ContactEmail    VARCHAR(254) NULL,
    Phone           VARCHAR(30) NULL,
    Address         VARCHAR(300) NULL,
    IsActive        BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt       TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    UpdatedAt       TIMESTAMPTZ(0) NULL,
    CONSTRAINT UQ_Companies_Rnc UNIQUE (Rnc)
);

CREATE TABLE Branches
(
    Id              INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Branches PRIMARY KEY,
    CompanyId       INT NOT NULL,
    Name            VARCHAR(150) NOT NULL,
