import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { db, ensureDatabaseExists } from './db.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const migrationsDir = path.resolve(__dirname, '../../database/migrations');

/**
 * Garantiza que la base de datos exista y aplica en orden (cada una dentro de una
 * transacción atómica) las migraciones .sql pendientes de database/migrations.
 */
export async function runMigrations() {
  await ensureDatabaseExists();

  await db.query(`
    CREATE TABLE IF NOT EXISTS SchemaMigrations (
      Id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      MigrationName VARCHAR(255) NOT NULL UNIQUE,
      AppliedAt TIMESTAMPTZ(0) NOT NULL DEFAULT now()
    );
  `);

  const files = (await fs.readdir(migrationsDir)).filter(name => name.endsWith('.sql')).sort();
  const applied = new Set((await db.query('SELECT MigrationName FROM SchemaMigrations;')).rows.map(row => row.MigrationName));
  const executed = [];

  for (const file of files) {
    if (applied.has(file)) continue;
    console.log(`[Migrations] Applying ${file}...`);
    const script = await fs.readFile(path.join(migrationsDir, file), 'utf8');
    await db.withTransaction(async tx => {
      try {
        await db.exec(script, tx.client);
      } catch (error) {
        console.error(`[Migrations] Error en ${file}: ${error.message}`);
        throw error;
      }
      await tx.query('INSERT INTO SchemaMigrations (MigrationName) VALUES (@name);', { name: file });
    });
    executed.push(file);
    console.log(`[Migrations] Successfully applied ${file}`);
  }
  return executed;
}
